-- Portfolio CMS v2: single versioned JSON document + contact inbox
-- Run this in Supabase SQL Editor after reviewing your existing policies.
create table if not exists public.portfolio_content (
  id smallint primary key default 1 check (id = 1),
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.portfolio_content enable row level security;
grant select on public.portfolio_content to anon, authenticated;
grant insert, update, delete on public.portfolio_content to authenticated;
drop policy if exists "portfolio content public read" on public.portfolio_content;
create policy "portfolio content public read" on public.portfolio_content
  for select to anon, authenticated using (true);
drop policy if exists "portfolio content admin write" on public.portfolio_content;
create policy "portfolio content admin write" on public.portfolio_content
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null check (char_length(email) between 5 and 254),
  subject text not null default '' check (char_length(subject) <= 200),
  message text not null check (char_length(message) between 5 and 10000),
  created_at timestamptz not null default now(),
  is_read boolean not null default false
);
alter table public.contact_messages enable row level security;
grant insert on public.contact_messages to anon, authenticated;
grant select, update, delete on public.contact_messages to authenticated;
grant usage, select on sequence public.contact_messages_id_seq to authenticated;
drop policy if exists "visitors submit contact messages" on public.contact_messages;
create policy "visitors submit contact messages" on public.contact_messages
  for insert to anon, authenticated
  with check (
    char_length(name) between 2 and 120
    and char_length(email) between 5 and 254
    and char_length(subject) <= 200
    and char_length(message) between 5 and 10000
  );
drop policy if exists "admins manage contact messages" on public.contact_messages;
create policy "admins manage contact messages" on public.contact_messages
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

